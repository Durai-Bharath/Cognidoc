"""Write a fully commented config.yaml from the Pydantic defaults.

Usage: python scripts/generate_config.py [overrides.yaml] > config.yaml
Every field's description becomes a comment, so each τ / w_k / limit is documented.
"""

from __future__ import annotations

import sys
from typing import Any

import yaml
from pydantic import BaseModel

from common.config import ExtractionConfig


def _scalar(value: Any) -> str:
    return (
        yaml.safe_dump(value, default_flow_style=True, allow_unicode=True, width=10**9)
        .strip()
        .removesuffix("\n...")
        .removesuffix("...")
        .strip()
    )


def render(model: BaseModel, indent: int = 0) -> list[str]:
    lines: list[str] = []
    pad = "  " * indent
    for name, field in type(model).model_fields.items():
        value = getattr(model, name)
        if field.description:
            lines.append(f"{pad}# {field.description}")
        if isinstance(value, BaseModel):
            lines.append(f"{pad}{name}:")
            lines.extend(render(value, indent + 1))
            lines.append("")
        elif isinstance(value, dict):
            lines.append(f"{pad}{name}:")
            for k, v in value.items():
                lines.append(f"{pad}  {_scalar(k)}: {_scalar(v)}")
        else:
            lines.append(f"{pad}{name}: {_scalar(value)}")
    return lines


def main() -> None:
    data: dict[str, Any] = {}
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf-8") as fh:
            data = yaml.safe_load(fh) or {}
    cfg = ExtractionConfig.model_validate(data)
    print("# Stage 1 extraction configuration. Generated by scripts/generate_config.py;")
    print("# every value below is the documented default unless noted in the header.")
    print("\n".join(render(cfg)).rstrip() + "\n")


if __name__ == "__main__":
    main()
